function h1(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_1,
    children: [new TextRun({ text, bold: true, size: 28, font: "Times New Roman" })],
    spacing: { before: 300, after: 200 }
  });
}

function h2(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_2,
    children: [new TextRun({ text, bold: true, size: 26, font: "Times New Roman" })],
    spacing: { before: 240, after: 160 }
  });
}

function h3(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_3,
    children: [new TextRun({ text, bold: true, size: 24, font: "Times New Roman" })],
    spacing: { before: 200, after: 120 }
  });
}

function p(text, opts = {}) {
  return new Paragraph({
    children: [new TextRun({ text, size: 24, font: "Times New Roman", ...opts })],
    spacing: { before: 100, after: 100, line: 276 },
    indent: { firstLine: 720 },
    alignment: AlignmentType.JUSTIFIED,
  });
}

function pBold(text) {
  return p(text, { bold: true });
}

function formula(text) {
  return new Paragraph({
    children: [new TextRun({ text, size: 24, font: "Courier New" })],
    spacing: { before: 120, after: 120, line: 276 },
    alignment: AlignmentType.CENTER,
  });
}

function caption(text) {
  return new Paragraph({
    children: [new TextRun({ text, size: 22, font: "Times New Roman", italics: true })],
    spacing: { before: 80, after: 160 },
    alignment: AlignmentType.CENTER,
  });
}

function makeTable(colWidths, headerCells, rows) {
  const total = colWidths.reduce((a, b) => a + b, 0);
  return new Table({
    width: { size: total, type: WidthType.DXA },
    columnWidths: colWidths,
    rows: [
      new TableRow({
        tableHeader: true,
        children: headerCells.map((text, i) =>
          new TableCell({
            borders, shading: headerShading, margins: cellM,
            width: { size: colWidths[i], type: WidthType.DXA },
            children: [new Paragraph({
              children: [new TextRun({ text, bold: true, size: 22, font: "Times New Roman" })],
              alignment: AlignmentType.CENTER,
            })]
          })
        )
      }),
      ...rows.map(row =>
        new TableRow({
          children: row.map((text, i) =>
            new TableCell({
              borders, margins: cellM,
              width: { size: colWidths[i], type: WidthType.DXA },
              children: [new Paragraph({
                children: [new TextRun({ text: text || "", size: 22, font: "Times New Roman" })],
                alignment: AlignmentType.LEFT,
              })]
            })
          )
        })
      )
    ]
  });
}

